import { expect, test, reloadAfterSave } from "./fixtures";
import { academicCatalogFixture, collection } from "./academicCatalogFixture";
import type { NoctyriumState } from "../src/lib/types";
import type { Page } from "@playwright/test";
const state = (page: Page) => page.evaluate(async () => {
  const dev = await (window as unknown as { __AXOM_DEV__: Promise<{ useStore: { getState: () => NoctyriumState }; flushVault: () => Promise<void> }> }).__AXOM_DEV__;
  await dev.flushVault(); const s = dev.useStore.getState();
  return { activities: s.tracker.filter(t => t.templateKey).map(t => t.id).sort(), questions: s.questions.map(q => q.id), attempts: s.questions.flatMap(q => q.attempts), images: s.questions.flatMap(q => q.attachments ?? []).length };
});
for (const width of [1440,390]) test(`one catalog links QBank to course weeks, images and saved answers at ${width}px`, async ({ page }) => {
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (["error","warning"].includes(message.type())) errors.push(message.text()); });
  await page.setViewportSize({ width, height: width===390 ? 844 : 900 });
  const backend = await academicCatalogFixture(page);
  const catalog = page.getByRole("region", { name: "Available question banks" });
  await catalog.scrollIntoViewIfNeeded();
  const card = catalog.locator(`[data-course-id="${collection}"]`);
  expect(await card.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  expect(await catalog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: `/tmp/axom-unified-qbank-${width}.png`, fullPage: true });
  await page.getByRole("region", { name: "Available question banks" }).locator(`[data-course-id="${collection}"]`).click();
  const plan = page.getByRole("region", { name: "GOER course plan" });
  await expect(plan).toBeVisible();
  await page.screenshot({ path: `/tmp/axom-unified-plan-${width}.png`, fullPage: true });
  await plan.getByRole("button", { name: "Clear selection", exact: true }).click();
  await expect(plan.getByRole("button", { name: "Load Course", exact: true })).toBeDisabled();
  await expect(plan.getByRole("button", { name: "Create Quiz", exact: true })).toBeDisabled();
  await plan.getByRole("checkbox", { name: "Week 2", exact: true }).check();
  await plan.getByRole("button", { name: "Load Course", exact: true }).click();
  await expect(page.getByText("Course downloaded and enrollment saved to your account.", { exact: true })).toBeVisible();
  const loaded = await state(page); expect(loaded.questions).toHaveLength(1); expect(loaded.activities).toHaveLength(2); expect(loaded.images).toBeGreaterThan(0);
  await plan.getByRole("button", { name: "Load Course", exact: true }).click();
  await expect(plan.getByRole("status")).toContainText("already in My Courses");
  expect(await state(page)).toEqual(loaded);
  expect(backend.paths).toContain("banks/test/assets/figure.png");
  await plan.getByRole("button", { name: "Quiz week 2", exact: true }).click();
  const stem = page.getByLabel("Question stem", { exact: true }); await expect(stem).toBeVisible();
  await expect.poll(() => stem.locator("img").first().evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0);
  await stem.focus(); await page.keyboard.press("A"); await page.keyboard.press("Enter");
  await page.getByRole("button", { name: "Finish block", exact: true }).click();
  const answered = await state(page); expect(answered.attempts).toHaveLength(1);
  await reloadAfterSave(page); expect(await state(page)).toEqual(answered);
  expect(await page.evaluate(() => document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
